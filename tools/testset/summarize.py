"""Markdown summary of results/testset_<set>.json -> results/testset_<set>.md (tables per group, failure modes).
Usage: python tools/testset/summarize.py drone"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SET = sys.argv[1] if len(sys.argv) > 1 else "drone"
doc = json.loads((ROOT / "results" / f"testset_{SET}.json").read_text())


def f(x, n=3):
    return "-" if x is None else (f"{x:.{n}f}" if isinstance(x, float) else str(x))


def failure_mode(c):
    """Coarse failure class from the report (status / stage / build reason)."""
    st = c.get("status")
    if st == "ok":
        return "ok"
    if st == "not_run":
        return "not run"
    if st == "crashed":
        return f"crash (rc={c.get('rc')}, likely OOM under the 7 GB cap)"
    if st == "running":
        return "still running (detached)"
    if st == "skipped":
        return "skipped: " + (c.get("skip") or "")[:60]
    if st == "exception":
        return f"engine exception: {(c.get('failure') or '')[:70]}"
    if st == "timeout":
        return f"timeout in {c.get('last_stage')}"
    txt = " ".join(str(c.get(k) or "") for k in ("failure", "build_reason"))
    if "cell decomposition exceeded" in txt:
        return "build: local trim failed, cell decomposition over 240 s budget"
    if "free" in txt and "edge" in txt:
        return "build: open shell (free edges after trim/sew)"
    if "no trimmed face" in txt:
        return "build: regions without trimmed face"
    if "deviation" in txt or c.get("gate_passed") is False:
        return "deviation gate failed"
    if "invalid" in txt.lower():
        return "build: invalid solid"
    return f"failed in {c.get('last_stage')}: {txt[:80]}"


inv = {r["file"]: r for r in doc["inventory"]}
lines = [f"# Test set `{SET}`: Flightory drone + VTOL parts", "",
         "Generated by `tools/testset/summarize.py` from `results/testset_%s.json` (numbers only, no geometry)." % SET, "",
         "Distances in mm. *truth* = STEP surface samples -> engine solid; *input* = engine input mesh vertices -> solid; "
         "volume error vs STEP truth (solid or glued solids the STL corresponds to).", ""]
for grp in ("drone", "vtol"):
    cs = [c for c in doc["cases"] if c.get("group") == grp]
    if not cs:
        continue
    lines += [f"## {grp}", "", "| case | input | truth | status | valid 1 solid | faces | vol err % | truth rms / p95 | input rms / p95 | time s | mode |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in sorted(cs, key=lambda c: (c.get("product") or "", c.get("input_kind") or "")):
        st_ = c.get("status")
        t = c.get("truth_to_solid") or {}
        i = c.get("input_to_solid") or {}
        truth = (inv.get(c.get("truth_step")) or {}).get("product", "-") if c.get("truth_step") else "-"
        if c.get("truth_solid") not in (None, -1):
            truth += f" #{c['truth_solid']}"
        lines.append(f"| {c.get('product')} | {c.get('input_kind')} | {truth} | {c.get('status')} | {c.get('valid_single_solid', '-')} | "
                     f"{c.get('n_faces', '-')} | {f(c.get('volume_err_pct'), 2)} | {f(t.get('rms'))} / {f(t.get('p95'))} | "
                     f"{f(i.get('rms'))} / {f(i.get('p95'))} | {c.get('wall_seconds') or (c.get('seconds') or ('>=600 (killed)' if st_ == 'timeout' else '-'))} | {failure_mode(c)} |")
    lines.append("")
modes = Counter(failure_mode(c).split(" (")[0] if failure_mode(c).startswith("skipped") else failure_mode(c) for c in doc["cases"])
lines += ["## Outcome counts", ""] + [f"- {k}: {v}" for k, v in modes.most_common()] + [""]
notes = Path(__file__).resolve().parent / f"notes_{SET}.md"
if notes.exists():
    lines += ["", notes.read_text()]
(ROOT / "results" / f"testset_{SET}.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
